import 'package:flutter/widgets.dart';

class AppStrings {
  AppStrings._(this.ko);
  AppStrings.testing(this.ko);
  final bool ko;
  static AppStrings of(BuildContext c) =>
      AppStrings._(Localizations.localeOf(c).languageCode == 'ko');
  String operator [](String key) => (ko ? _ko : _en)[key] ?? key;
  String fmt(String key, Map<String, Object> args) {
    var value = this[key];
    for (final entry in args.entries) {
      value = value.replaceAll('{${entry.key}}', entry.value.toString());
    }
    return value;
  }

  String get localeCode => ko ? 'ko' : 'en';
}

